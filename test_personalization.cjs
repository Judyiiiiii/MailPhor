const assert=require('node:assert/strict');
const P=require('./personalization.js');
const storage={values:new Map(),getItem(key){return this.values.get(key)??null;},setItem(key,value){this.values.set(key,value);}};
let state=P.read(storage);
const fixture={id:'one',title:'Embedded AI with Python',category:'competition',subcategory:'',tags:['hardware'],details:{eligibility:'Year 3+; CGPA 3.5'},deadline:'2026-10-25'};
assert.equal(P.evaluate(fixture,null).level,'pending');
const profile={major:'Electronic and Electrical Engineering',year:'2',gpa:'',skills:['C++','Python'],goals:['project','internship'],interests:['technical'],exploration:'open'};
const result=P.evaluate(fixture,profile);
assert.equal(result.qualification,'存在明确不符合项');
assert.equal(result.level,'low');
assert.ok(result.checks.some(text=>text.includes('GPA 未填写')));
const sports={id:'sport',category:'event',subcategory:'sports_wellness',title:'Marathon'};
assert.equal(P.evaluate(sports,{goals:['wellness'],interests:['sports_wellness']}).level,'high');
const technical=P.evaluate({...fixture,details:{}},profile);
assert.equal(technical.level,'high');
assert.equal(technical.qualification,'未发现明确资格要求');
assert.equal(P.evaluate({title:'Career Fair',category:'event'}, {...profile,skills:['AI'],goals:[],interests:[],exploration:'focused'}).level,'low','AI must not match the letters in Fair');
state={...state,profile};
state=P.updateAction(state,'one',{favorite:true,status:'applied',checked:{'准备 CV':true}});
P.save(storage,state);
const restored=P.read(storage);
assert.equal(restored.actions.one.favorite,true);
assert.equal(restored.actions.one.checked['准备 CV'],true);
assert.equal(restored.actions.one.status,'applied');
assert.equal(restored.profile.year,'2');
assert.equal(P.evaluate({...fixture,details:{}},profile,{feedback:'not_interested'}).level,'low');
assert.equal(P.deadlineValue({deadline:'Unknown'}),Infinity);
assert.equal(P.deadlineValue({deadline:'2026-02-30'}),Infinity);
assert.ok(Number.isFinite(P.deadlineValue(fixture)));
const bad={getItem:()=>'{broken'};
assert.throws(()=>P.read(bad));
const denied={setItem:()=>{throw Error('quota');}};
assert.throws(()=>P.save(denied,state));
P.save(storage,{version:1,profile:{major:'Demo'},actions:{}},P.KEY+'.demo');
assert.equal(P.read(storage).profile.major,profile.major,'Demo cannot overwrite real profile');
assert.equal(P.read(storage,P.KEY+'.demo').profile.major,'Demo');
const weaker={id:'weak',category:'event',title:'General Campus Event',details:{}};
const stronger={id:'strong',category:'event',title:'Python Workshop',details:{}};
const openProfile={skills:['Python'],goals:[],interests:[],exploration:'open'};
assert.equal(P.evaluate(weaker,openProfile).level,P.evaluate(stronger,openProfile).level);
assert.deepEqual([weaker,stronger].sort((a,b)=>P.comparePriority(a,b,openProfile)).map(item=>item.id),['strong','weak']);
const ee={id:'ee',category:'event',title:'EEHS Recruitment',details:{}};
assert.ok(P.evaluate(ee,profile).reasons.some(reason=>reason.includes('专业方向')));
const projectCard={...fixture,details:{}};
const sportsProfile={goals:['wellness'],interests:['sports_wellness'],skills:[],exploration:'focused'};
assert.equal([projectCard,sports].sort((a,b)=>P.comparePriority(a,b,profile))[0].id,projectCard.id);
assert.equal([projectCard,sports].sort((a,b)=>P.comparePriority(a,b,sportsProfile))[0].id,sports.id);
console.log('Personalization checks passed: preferences, unknown GPA, year mismatch, skill boundaries, state persistence, feedback, deadline sorting and storage failures.');
